/* Form factor lookup table parameters */
const FF_TABLE_SIZE = 10000;
const FF_Q_MAX = 4.0 * Math.PI / 0.2;   /* q_max for λ_min = 0.2 Å ≈ 62.83 Å⁻¹ */

/**
 * Compute a form factor lookup table f(q) for q ∈ [0, FF_Q_MAX].
 * Returns a Float32Array of FF_TABLE_SIZE values.
 */
function computeFormFactorTable(atom) {
    const table = new Float32Array(FF_TABLE_SIZE);
    const inv16pi2 = 1.0 / (16.0 * Math.PI * Math.PI);
    for (let i = 0; i < FF_TABLE_SIZE; i++) {
        const q = (i / (FF_TABLE_SIZE - 1)) * FF_Q_MAX;
        const q2 = q * q * inv16pi2;
        let f = atom.c;
        for (let j = 0; j < 4; j++) {
            f += atom.a[j] * Math.exp(-atom.b[j] * q2);
        }
        table[i] = f;
    }
    return table;
}

/**
 * Search atoms by symbol prefix, name prefix, or atomic number prefix.
 * Returns up to 12 matching ATOM_DATA entries.
 */
function searchAtoms(query) {
    query = query.trim();
    if (!query) return [];
    const num = parseInt(query);
    if (!isNaN(num)) {
        return ATOM_DATA.filter(a => a.Z.toString().startsWith(query)).slice(0, 12);
    }
    const lower = query.toLowerCase();
    return ATOM_DATA.filter(a =>
        a.sym.toLowerCase().startsWith(lower) ||
        a.name.toLowerCase().startsWith(lower)
    ).slice(0, 12);
}
